"""Writes a pip lock file (exact versions and SHA-256 hashes) from an
installed environment, so the online installer recreates it package for
package with `pip install --no-deps --require-hashes -r <lock>`.

PyTorch packages (local versions such as 2.10.0+cu128) are written to their
own files, one per build (cu128 and cpu), with hashes read from
download.pytorch.org.

    python installer/scripts/make-lock.py <site-packages> <output.txt> [--torch-out <prefix>]
"""
import argparse
import html.parser
import json
import os
import re
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

TORCH = {"torch", "torchaudio", "torchvision"}
SKIP = {"pip"}
# Packages installed from a direct URL instead of PyPI: name -> (url, sha256).
DIRECT = {}


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def installed(site):
    rows = []
    site = Path(site).resolve()
    if os.name == "nt" and not str(site).startswith("\\\\?\\"):
        site = Path("\\\\?\\" + str(site))
    for info in sorted(site.glob("*.dist-info")):
        meta = (info / "METADATA").read_text(encoding="utf-8", errors="replace").splitlines()
        name = next(l.split(":", 1)[1].strip() for l in meta if l.startswith("Name:"))
        version = next(l.split(":", 1)[1].strip() for l in meta if l.startswith("Version:"))
        direct = info / "direct_url.json"
        url = json.loads(direct.read_text())["url"] if direct.is_file() else ""
        rows.append((name, version, url))
    return rows


def pypi_hashes(name, version):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        files = json.load(r)["urls"]
    return sorted({f["digests"]["sha256"] for f in files})


class Links(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            self.links.append(dict(attrs).get("href", ""))


def torch_files(name, version, build):
    """Windows and Linux wheels of one PyTorch build, with their hashes."""
    with urllib.request.urlopen(f"https://download.pytorch.org/whl/{build}/{name}/", timeout=60) as r:
        page = Links()
        page.feed(r.read().decode())
    want = f"{name}-{version}+{build}-"
    out = []
    for href in page.links:
        file = urllib.parse.unquote(href.split("/")[-1].split("#")[0])
        if file.startswith(want) and "cp312" in file and ("win_amd64" in file or "x86_64" in file):
            out.append(href.split("#sha256=")[1])
    return sorted(set(out))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("site")
    parser.add_argument("output", type=Path)
    parser.add_argument("--torch-out", help="prefix for the PyTorch lock files, e.g. installer/locks/speech-torch")
    parser.add_argument("--direct", nargs="*", default=[], help="name=url#sha256 for packages not on PyPI")
    args = parser.parse_args()
    direct = dict(DIRECT)
    for item in args.direct:
        name, rest = item.split("=", 1)
        url, sha = rest.split("#sha256=")
        direct[norm(name)] = (url, sha)

    rows = [r for r in installed(args.site) if norm(r[0]) not in SKIP]
    torch = [r for r in rows if norm(r[0]) in TORCH]
    plain = [r for r in rows if norm(r[0]) not in TORCH]

    def line(row):
        name, version, _ = row
        if norm(name) in direct:
            url, sha = direct[norm(name)]
            return f"{name} @ {url} --hash=sha256:{sha}"
        hashes = pypi_hashes(name, version)
        if not hashes:
            raise SystemExit(f"{name} {version}: no files on PyPI")
        return f"{name}=={version} " + " ".join(f"--hash=sha256:{h}" for h in hashes)

    with ThreadPoolExecutor(12) as pool:
        lines = list(pool.map(line, plain))
    header = "# Generated by installer/scripts/make-lock.py. Install with --no-deps --require-hashes.\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{args.output}: {len(lines)} packages")
    if torch and args.torch_out:
        for build in ("cu128", "cpu"):
            out = []
            for name, version, _ in torch:
                base = version.split("+")[0]
                hashes = torch_files(norm(name), base, build)
                if not hashes:
                    raise SystemExit(f"{name} {base}+{build}: not on download.pytorch.org")
                out.append(f"{name}=={base}+{build} " + " ".join(f"--hash=sha256:{h}" for h in hashes))
            path = Path(f"{args.torch_out}-{build}.txt")
            path.write_text(header + f"# --index-url https://download.pytorch.org/whl/{build}\n" + "\n".join(out) + "\n", encoding="utf-8")
            print(f"{path}: {', '.join(r[0] for r in torch)}")


if __name__ == "__main__":
    main()
